const DICTS: Record<Lang, Dict> = { en, fr, ar, es };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  const template = DICTS[lang]?.[key] ?? en[key] ?? key;
  return vars ? template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : template;
}

export function plural(lang: Lang, base: "prop.brands", n: number): string {
  const one = new Intl.PluralRules(intlLocale(lang)).select(n) === "one";
  return translate(lang, `${base}_${one ? "one" : "other"}` as MessageKey, { n });
}

const isLang = (v: string): v is Lang => LANGS.some((l) => l.code === v);

/** First supported language from a list like navigator.languages (["fr-FR", "en"]). */
export function pickLang(candidates: readonly string[]): Lang {
  for (const c of candidates) {
    const base = c.toLowerCase().split(/[-_]/)[0];
    if (isLang(base)) return base;
  }
  return DEFAULT_LANG;
}

/** Language for a server request: explicit x-lang header first, then Accept-Language. */
export function langFromRequest(headers: Headers): Lang {
  const explicit = headers.get("x-lang");
  if (explicit && isLang(explicit)) return explicit;
  const accept = headers.get("accept-language") ?? "";
  const ranked = accept
    .split(",")
    .map((part) => {
      const [tag, q] = part.trim().split(";q=");
      return { tag, q: q ? Number(q) : 1 };
    })
    .filter((x) => x.tag)
    .sort((a, b) => b.q - a.q)
    .map((x) => x.tag);
  return pickLang(ranked);
}
